"""
wake_word.py
Voice-only conversational layer.

The existing dashboard/interface is intentionally untouched. Safety alerts are
still generated by the existing fusion loop without a wake word. This module
only listens for the conversational wake word and then captures a short voice
command for Gemini.
"""

import logging
import threading
import time
import wave
from pathlib import Path

import config

logger = logging.getLogger("obstacle_assistance.wake_word")


class WakeWordAssistant:
    def __init__(self, agent, voice, context_provider, enabled=None):
        self.agent = agent
        self.voice = voice
        self.context_provider = context_provider
        self.enabled = config.WAKEWORD_ENABLED if enabled is None else enabled
        self.threshold = config.WAKEWORD_THRESHOLD
        self.command_seconds = config.COMMAND_SECONDS
        self._stop_event = threading.Event()
        self._wake_event = threading.Event()
        self._thread = None
        self._running = False
        self._busy = threading.Event()

    @property
    def running(self):
        return self._running

    def start(self):
        if not self.enabled or self._thread is not None:
            return
        if not self.agent.configured:
            logger.info("Wake word disabled because GEMINI_API_KEY is not configured")
            return

        self._thread = threading.Thread(target=self._run, daemon=True)
        self._thread.start()

    def stop(self):
        self._stop_event.set()
        self._wake_event.set()

    def _run(self):
        self._running = True
        try:
            import numpy as np
            import sounddevice as sd
            from openwakeword.model import Model

            model = Model(wakeword_models=[config.WAKEWORD_MODEL])
            samplerate = 16000
            blocksize = 1280

            def callback(indata, frames, time_info, status):
                if status:
                    logger.debug("Wake word audio status: %s", status)
                if self._busy.is_set() or self._stop_event.is_set():
                    return
                try:
                    audio = np.asarray(indata[:, 0], dtype=np.int16)
                    scores = model.predict(audio)
                    score = self._extract_score(scores)
                    if score >= self.threshold:
                        self._wake_event.set()
                except Exception:
                    logger.exception("Wake word callback error")

            logger.info("Wake word listener started: %s", config.WAKEWORD_MODEL)
            with sd.InputStream(
                samplerate=samplerate,
                blocksize=blocksize,
                channels=1,
                dtype="int16",
                callback=callback,
            ):
                while not self._stop_event.is_set():
                    if self._wake_event.wait(0.25):
                        self._wake_event.clear()
                        if self._busy.is_set():
                            continue
                        self._handle_activation(samplerate)
        except ImportError as exc:
            logger.error("Wake word dependencies are missing: %s", exc)
        except Exception as exc:
            logger.exception("Wake word listener stopped: %s", exc)
        finally:
            self._running = False

    @staticmethod
    def _extract_score(scores):
        if isinstance(scores, dict):
            values = [float(v) for v in scores.values() if isinstance(v, (int, float))]
            return max(values, default=0.0)
        return 0.0

    def _handle_activation(self, samplerate):
        self._busy.set()
        try:
            self.voice.speak_text("I'm listening.")
            audio_path = self._record_command(samplerate)
            if audio_path is None:
                self.voice.speak_text("I didn't hear a command.")
                return

            text = self._transcribe(audio_path)
            try:
                Path(audio_path).unlink(missing_ok=True)
            except Exception:
                pass

            if not text:
                self.voice.speak_text("I didn't understand that.")
                return

            logger.info("Voice command: %s", text)
            context = self.context_provider() if self.agent.is_scene_question(text) else ""
            answer = self.agent.ask(text, context)
            self.voice.speak_text(answer)
        finally:
            self._busy.clear()

    def _record_command(self, samplerate):
        try:
            import numpy as np
            import sounddevice as sd

            self.voice.speak_text("Go ahead.")
            frames = int(samplerate * self.command_seconds)
            recording = sd.rec(
                frames,
                samplerate=samplerate,
                channels=1,
                dtype="int16",
                blocking=True,
            )

            path = Path(config.WAKEWORD_TEMP_WAV)
            path.parent.mkdir(parents=True, exist_ok=True)
            with wave.open(str(path), "wb") as wav:
                wav.setnchannels(1)
                wav.setsampwidth(2)
                wav.setframerate(samplerate)
                wav.writeframes(np.asarray(recording, dtype=np.int16).tobytes())
            return str(path)
        except Exception:
            logger.exception("Command recording failed")
            return None

    @staticmethod
    def _transcribe(audio_path):
        try:
            import speech_recognition as sr
            recognizer = sr.Recognizer()
            with sr.AudioFile(audio_path) as source:
                audio = recognizer.record(source)
            return recognizer.recognize_google(audio)
        except Exception as exc:
            logger.warning("Speech recognition failed: %s", exc)
            return ""
